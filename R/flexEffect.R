#' Flexible Causal Path-Specific Effect Estimation
#'
#' This function estimates causal path-specific effects by comparing two potential outcome objects generated from the \code{flexMean} or \code{mflexMean} functions.
#' The effects can be estimated on different scales, including difference ("diff"), risk ratio ("risk"), and odds ratio ("oddsratio").
#' The function also supports bootstrapping for standard errors and confidence
#' intervals on all scales, with p-values on the difference scale.
#'
#' @param p1 An object or a list of objects of class \code{flexMean} or \code{mflexMean} generated by the \code{flexMean} or \code{mflexMean} function, representing one set of potential outcomes.
#' @param p0 An object or a list of objects of class \code{flexMean} or \code{mflexMean} generated by the \code{flexMean} or \code{mflexMean} function, representing another set of potential outcomes for comparison.
#' All objects in \code{p1} and \code{p0} must have the same class: either all
#' \code{flexMean} or all \code{mflexMean}.
#' The two inputs should have the same length; otherwise, one of them must
#' contain a single potential outcome object.
#' @param scale A character string specifying the scale for effect estimation. Options are "diff" (difference), "risk" (risk ratio), and "oddsratio" (odds ratio). The default is "diff".
#' Direct standard errors, confidence intervals, and p-values are returned only
#' for EIF estimation with \code{scale = "diff"}. Otherwise, use \code{nboot}
#' for bootstrap standard errors and confidence intervals.
#' @param CI_level A numeric value indicating the confidence level for the confidence intervals, typically set between 0 and 1. The default is 0.95 for 95% confidence intervals.
#' @param nboot An optional numeric value specifying the number of bootstrap samples to draw for estimating the standard errors and confidence intervals. If NULL, no bootstrapping is performed.
#' @param m.cores An optional numeric value indicating the number of cores to use for parallel processing during bootstrapping. If NULL, the function will use a single core.
#'
#' @return An object of class \code{flexEffect}, which includes the following components:
#' \describe{
#'   \item{\code{pathsInfo}}{The original \code{pathsInfo} object used for the analysis.}
#'   \item{\code{results}}{A data frame containing the estimated effects for each path.
#'   SE, CI.lower, CI.upper, and P.value are included only for EIF estimation
#'   with \code{scale = "diff"}; otherwise, these columns are omitted.}
#'   \item{\code{data}}{The original data frame used for the analysis.}
#'   \item{\code{boot_results}}{If bootstrapping is performed, a data frame containing
#'   the effect estimates, bootstrap standard errors and percentile confidence intervals.
#'   P-values based on a normal approximation using the bootstrap standard errors
#'   are included only for \code{scale = "diff"}.}
#'   \item{\code{call}}{The matched call to the \code{flexEffect} function.}
#' }
#'
#'
#' @import stats purrr
#' @import SuperLearner dbarts
#' @importFrom dplyr %>% arrange select mutate group_by summarise full_join join_by relocate
#' @importFrom parallel mclapply detectCores
#'
#' @export
#'
#' @example inst/examples/flexEffect-example.R
#'
flexEffect <- function(
  p1,
  p0,
  scale = "diff", CI_level = 0.95,
  nboot = NULL, m.cores = NULL) {

  # environment
  Call <- match.call()
  # Column names used in dplyr expressions.
  assign <- value1 <- value0 <- comparison_id <- Effect <- NULL

  # 1. check the input p1 and p0 -----
  ## (1) to check one input -------
  if (is.null(p1$call)) {len_p1 <- length(p1) } else {
    p1 = list(p1)
    len_p1 <- length(p1)}
  if (is.null(p0$call)) {len_p0 <- length(p0)} else {
    p0 = list(p0)
    len_p0 <- length(p0)}

  if (len_p1 != len_p0) {
    # 2. If lengths differ, one of them must have exactly one input
    if (len_p1 == 1) {
      p1 <- rep(p1, len_p0)
    } else if (len_p0 == 1) {
      p0 <- rep(p0, len_p1)
    } else {
      stop("p1 and p0 must have the same length or one of them must have only one input.")
    }
  }


  ## (2). Check that the Call components of p1, and p0 ----
  # same class flexMean or mflexMean
  class_p = map_chr(c(p1, p0), ~ class(.x))

  if (length(unique(class_p)) != 1) {
    stop("All elements in p1 and p0 must have the same class.")
  }
  if (!unique(class_p) %in% c("flexMean", "mflexMean")) {
    stop("All elements in p1 and p0 the class must be either 'flexMean' or 'mflexMean'.")

  }


  # they have the pathsInfo
  pathsInfo_p1 <- map(p1, ~ .x$pathsInfo)
  pathsInfo_p0 <- map(p0, ~ .x$pathsInfo)

  if (!all(map_lgl(pathsInfo_p1, ~ identical(.x, pathsInfo_p0[[1]])))) {
    stop("All inputs in p1 and p0 must have the same 'pathsInfo' in their Call component.")
  }

  # 2. calculate effects
  results <- map2_dfr(p1, p0, ~ {
    assign <- paste(.x$results$assign, "vs", .y$results$assign)

    if (scale == "diff") {
      diff <- .x$potential_data - .y$potential_data
      Effect <- mean(diff, na.rm = TRUE)
      if (.x$pathsInfo$estimation == "EIF") {
        SE <- sqrt(var(diff, na.rm = TRUE) / length(diff))
        CI.lower <- Effect + qnorm((1 - CI_level) / 2) * SE
        CI.upper <- Effect - qnorm((1 - CI_level) / 2) * SE
        P.value <- round(2 * (1 - pnorm(abs(Effect / SE))), 4)

    # Return the results as a data frame row
        out <- data.frame(assign = assign, Effect = Effect, SE = SE, CI.lower = CI.lower, CI.upper = CI.upper, P.value = P.value)
      } else {
        out <- data.frame(assign = assign, Effect = Effect)
      }
    }

    if (scale == "risk") {
      Effect <- mean(.x$potential_data, na.rm = TRUE) / mean(.y$potential_data, na.rm = TRUE)
    # Return the results as a data frame row
      out <- data.frame(assign = assign, Effect = Effect)
    }

    if (scale == "oddsratio") {
      m1 <- mean(.x$potential_data, na.rm = TRUE)
      m2 <- mean(.y$potential_data, na.rm = TRUE)
      Effect <- (m1 / (1 - m1)) / (m2 / (1 - m2))

      out <- data.frame(assign = assign, Effect = Effect)
    }

    return(out) })

  data_raw = p1[[1]]$pathsInfo$data; pathsInfo = p1[[1]]$pathsInfo
  out <- list(pathsInfo = pathsInfo,
    results = arrange(results, by = assign),
    data = data_raw)

  # 2. get the summary of identical calculation ----
  # check_SuperLearner return warning
  if (!is.null(nboot)) {

    results$comparison_id <- seq_len(nrow(results))

  # aviod replicate calculation to save time
    call_p1 <- map(p1, ~ .x$call)
    call_p0 <- map(p0, ~ .x$call)
    call_all <- unique(c(call_p1, call_p0))

    index_p1 <- map_int(call_p1, function(index) {
      which(map_lgl(call_all, ~ identical(.x, index)))
    })
    index_p0 <- map_int(call_p0, function(index) {
      which(map_lgl(call_all, ~ identical(.x, index)))
    })

  # bootstrap
    if (is.numeric(m.cores)) {
      m.cores.detected <- parallel::detectCores()
      if (m.cores > m.cores.detected) {m.cores <- m.cores.detected}

    # windows, m.cores = 1
      os <- tolower(Sys.info()[['sysname']])
      if (os == "windows") {
        m.cores <- 1
        message("Running on Windows. Setting cores to 1 since mclapply is not available.")
      }

    # run
      boot.list <- parallel::mclapply(seq_len(nboot), function(i) {
        one_boot.flexEffect(data_raw, pathsInfo, call_all, index_p1, index_p0)}, mc.cores = m.cores)
    } else {
      boot.list = map(seq_len(nboot),
        ~ one_boot.flexEffect(data_raw, pathsInfo, call_all, index_p1, index_p0))
    }

    results.combine <- map_dfr(boot.list, ~.x, .id = "source")
    output <- results.combine %>%
      mutate(
        Effect = if (scale == "diff") {
          value1 - value0
        } else if (scale == "risk") {
          value1 / value0
        } else if (scale == "oddsratio") {
          (value1 / (1 - value1)) / (value0 / (1 - value0))
        }
      ) %>%
      group_by(comparison_id) %>%
      summarise(
        boot.SE = sd(Effect),
        boot.CI.lower = quantile(Effect, probs = (1 - CI_level) / 2),
        boot.CI.upper = quantile(Effect, probs = 1 - (1 - CI_level) / 2)) %>%
      full_join(select(results, comparison_id, assign, Effect), by = join_by(comparison_id)) %>%
      arrange(assign) %>%
      select(-comparison_id) %>%
      mutate(nboot = nboot) %>%
      relocate(assign, Effect) %>% as.data.frame()

    if (scale == "diff") {output$boot.P.value = round(2 * (1 - pnorm(abs(output$Effect) / output$boot.SE)), 4)}

    out$boot_results <- output


  }

  out$call <- Call
  class(out) <- "flexEffect"
  return(out)

}


